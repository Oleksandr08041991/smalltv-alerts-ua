#!/usr/bin/env python3
"""Build a 4-bit PROGMEM airplane atlas from the REAL mascotPixel() geometry.

A 240x240 ESP8266 has no frame buffer. Evaluating ~40 geometry tests twice
for every output pixel makes the aircraft redraw over several seconds.
Generate 12 high-detail facial/wing poses offline on the BUILD COMPUTER;
firmware samples them from FLASH, not the scarce ~80 KiB ESP8266 RAM.

Each 159x117 pose uses 9302 bytes (4-bit palette). Three wing perspectives,
two expressions, and blinking/open eyes = 12 poses / ~109 KiB Flash.
The 20 motion trajectories and continuous bank/scale/yaw still run on-chip.

Requires a host C++ compiler (c++ or CXX) when building the ESP8266 image.
"""
from pathlib import Path
import os
import re
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src/features/mascot/MascotMode.cpp"
DEST = ROOT / "src/features/mascot/PlaneAtlas.generated.h"
WIDTH, HEIGHT = 159, 117
PIXELS = WIDTH * HEIGHT
STRIDE = (PIXELS + 1) // 2
POSES = 12
YAW = (-24, 0, 24)


def cpp_source():
    src = SOURCE.read_text(encoding="utf-8")
    start = src.index("static inline bool disc(")
    end = src.index("static uint16_t mascotColor(", start)
    geometry = src[start:end]
    # Do not copy an approximation of the picture. Compile the very same
    # polygons, eye logic, wing shadows and undercarriage as in firmware.
    if "static uint8_t mascotPixel(" not in geometry:
        raise RuntimeError("Airplane renderer has changed; regenerate deliberately")
    return r"""
#include <algorithm>
#include <cstdint>
#include <cstdlib>
#include <cstdio>
using std::min;
using std::max;
using std::abs;
""" + geometry + r"""
int main() {
  for(int yawIndex=0;yawIndex<3;yawIndex++){
    for(int expression=0;expression<2;expression++){
      for(int eye=0;eye<2;eye++){
        // 0: smile; 7: open-mouth pose. The original function also varies
        // wing-tip flex as its normal animation does.
        const uint32_t frame=expression?7u:0u;
        const uint16_t speech=(uint16_t)((29u-(frame/2u)%29u + (eye?1u:0u))%29u);
        int high=-1;
        for(int y=-57;y<=59;y++)for(int x=-79;x<=79;x++){
          uint8_t c=mascotPixel(x,y,frame,0u,speech,
                               (int8_t)(yawIndex==0?-24:yawIndex==1?0:24));
          if(c>13u)return 2;
          if(high<0)high=c;
          else {
            unsigned char b=(unsigned char)((high<<4)|c);
            if(std::fwrite(&b,1,1,stdout)!=1)return 3;
            high=-1;
          }
        }
        if(high>=0){
          const unsigned char b=(unsigned char)(high<<4);
          if(std::fwrite(&b,1,1,stdout)!=1)return 4;
        }
      }
    }
  }
  return 0;
}
"""


def generate():
    with tempfile.TemporaryDirectory(prefix="smalltv-plane-") as temp:
        binary = Path(temp) / ("plane-atlas.exe" if os.name == "nt" else "plane-atlas")
        compiler = os.environ.get("CXX", "c++")
        proc = subprocess.run(
            [compiler, "-x", "c++", "-std=c++11", "-O2", "-o", str(binary), "-"],
            input=cpp_source(), encoding="utf-8", capture_output=True
        )
        if proc.returncode:
            raise RuntimeError(f"Host C++ airplane-atlas compiler failed:\n{proc.stderr}")
        raw = subprocess.check_output([str(binary)])
    if len(raw) != STRIDE * POSES:
        raise RuntimeError(f"Plane atlas is {len(raw)} bytes, expected {STRIDE*POSES}")
    prefix = """// GENERATED by tools/generate_plane_atlas.py from MascotMode.cpp.
// DO NOT EDIT. These are the SAME detailed aircraft pixels used by the
// procedural fallback, but packed into ESP8266 Flash rather than RAM.
// Three yaw poses x two expressions x two eye states.
#pragma once
#include <Arduino.h>
namespace planeflash {
constexpr int kWidth=159;
constexpr int kHeight=117;
constexpr int kStride=9302;
constexpr int kPoseCount=12;
static const uint8_t frames[] PROGMEM = {
"""
    # Small regular rows are compiler-friendly. 4 bits/pixel, exact palette.
    lines = [
        "  " + ",".join(f"0x{x:02X}" for x in raw[i:i+32]) + ","
        for i in range(0, len(raw), 32)
    ]
    content = prefix + "\n".join(lines) + "\n};\n} // namespace planeflash\n"
    if "--check" in sys.argv:
        if not DEST.exists() or DEST.read_text(encoding="utf-8") != content:
            raise SystemExit("Airplane atlas missing or out of date")
    elif not DEST.exists() or DEST.read_text(encoding="utf-8") != content:
        DEST.write_text(content, encoding="utf-8")
    print(f"Airplane atlas: {POSES} detailed poses, {len(raw):,} bytes Flash, 0 bytes heap")


if __name__ == "__main__":
    generate()
